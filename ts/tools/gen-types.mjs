// Sync the erupt schemas into src/ and generate src/types.ts from them.
//
//   node tools/gen-types.mjs <erupt repo>/schema          copy schemas, regenerate types
//   node tools/gen-types.mjs <erupt repo>/schema --check  fail when anything is out of date (CI)
//
// Inputs are generated in the erupt repository by erupt-test NodeSchemaTest (annotation JSON Schema) and
// NodeDefaultsTest (resolved field templates).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "src");

// erupt schema file -> package copy
const SCHEMAS = {
  "erupt-annotations.schema.json": join(SRC, "schema.json"),
  "erupt-node-defaults.json": join(SRC, "defaults.json"),
};

const PRIMITIVES = { string: "string", integer: "number", number: "number", boolean: "boolean" };

function tsType(schema) {
  if (schema.$ref) return schema.$ref.split("/").pop();
  switch (schema.type) {
    case "array":
      return `${tsType(schema.items)}[]`;
    case "object":
      return schema.additionalProperties ? `Record<string, ${tsType(schema.additionalProperties)}>` : "Record<string, unknown>";
    default:
      return PRIMITIVES[schema.type];
  }
}

function doc(schema) {
  const notes = [];
  if ("default" in schema) notes.push("default " + JSON.stringify(schema.default));
  if (schema["x-erupt-match"]) notes.push("only when " + schema["x-erupt-match"]);
  if (schema["x-erupt-map-key"]) notes.push("keyed by " + schema["x-erupt-map-key"]);
  return notes.length ? `  /** ${notes.join("; ").replaceAll("*/", "*\\/")} */\n` : "";
}

export function generate(schema) {
  const out = [
    "// Erupt annotation JSON as TypeScript types. Generated by tools/gen-types.mjs from",
    "// erupt-annotations.schema.json; do not edit. Every key is optional: a declaration only overrides",
    "// the defaults the Java proxies emit. `<Enum>Values` lists an enum's values for runtime checks.",
  ];
  const defs = Object.entries(schema.$defs);
  for (const [name, def] of defs) {
    if (!def.enum) continue;
    out.push("", `export const ${name}Values = ${JSON.stringify(def.enum)} as const;`,
      `export type ${name} = (typeof ${name}Values)[number];`);
  }
  for (const [name, def] of defs) {
    if (def.enum) continue;
    out.push("", `export interface ${name} {`);
    for (const [prop, s] of Object.entries(def.properties)) {
      const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(prop) ? prop : JSON.stringify(prop);
      out.push(`${doc(s)}  ${key}?: ${tsType(s)};`);
    }
    out.push("}");
  }
  return out.join("\n") + "\n";
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const dir = args.find((a) => !a.startsWith("--"));
  if (!dir) {
    console.error("usage: node tools/gen-types.mjs <erupt repo>/schema [--check]");
    process.exit(2);
  }
  const expected = new Map();
  for (const [source, target] of Object.entries(SCHEMAS)) {
    const path = resolve(dir, source);
    if (!existsSync(path)) {
      console.error(`missing ${path}`);
      process.exit(1);
    }
    expected.set(target, readFileSync(path, "utf8"));
  }
  expected.set(join(SRC, "types.ts"), generate(JSON.parse(expected.get(join(SRC, "schema.json")))));
  const stale = [...expected].filter(([p, text]) => !existsSync(p) || readFileSync(p, "utf8") !== text);
  for (const [p, text] of stale) {
    if (check) console.log(`stale: ${relative(ROOT, p)}`);
    else {
      writeFileSync(p, text);
      console.log(`wrote ${relative(ROOT, p)}`);
    }
  }
  if (check && stale.length) process.exit(1);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
