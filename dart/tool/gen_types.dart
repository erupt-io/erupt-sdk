// Embeds the erupt schemas into the package and generates lib/src/types.g.dart from them.
//
//   dart run tool/gen_types.dart ../schema          embed schemas, regenerate types
//   dart run tool/gen_types.dart ../schema --check  fail when anything is out of date (CI)
//
// Inputs are generated in the erupt repository by erupt-test NodeSchemaTest (annotation JSON Schema) and
// NodeDefaultsTest (resolved field templates). A Dart package cannot read a resource file after AOT
// compilation, so both are embedded as string constants.
import 'dart:convert';
import 'dart:io';

const _header = 'Generated by tool/gen_types.dart from erupt-annotations.schema.json; do not edit.';

const _primitives = {'string': 'String', 'integer': 'int', 'number': 'num', 'boolean': 'bool'};

// attribute names Dart does not take as a member name
const _renamed = {'dynamic', 'operator'};

String _member(String prop) => _renamed.contains(prop) ? '${prop}_' : prop;

String _dartType(Map<String, dynamic> schema) {
  final ref = schema[r'$ref'] as String?;
  if (ref != null) return ref.split('/').last;
  return switch (schema['type']) {
    'array' => 'List<${_dartType(schema['items'] as Map<String, dynamic>)}>',
    'object' => schema['additionalProperties'] is Map
        ? 'Map<String, ${_dartType(schema['additionalProperties'] as Map<String, dynamic>)}>'
        : 'Map<String, Object?>',
    final type => _primitives[type]!,
  };
}

String _note(Map<String, dynamic> schema) {
  final notes = [
    if (schema.containsKey('default')) 'default ${jsonEncode(schema['default'])}',
    if (schema['x-erupt-match'] != null) 'only when ${schema['x-erupt-match']}',
    if (schema['x-erupt-map-key'] != null) 'keyed by ${schema['x-erupt-map-key']}',
  ];
  return notes.isEmpty ? '' : '  /// ${notes.join('; ')}\n';
}

String generateTypes(Map<String, dynamic> schema) {
  final defs = (schema[r'$defs'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
  final out = StringBuffer()
    ..writeln('// $_header')
    ..writeln('// Every attribute is optional: a declaration only overrides the defaults the Java proxies emit.')
    ..writeln('// ignore_for_file: constant_identifier_names, non_constant_identifier_names')
    ..writeln("import 'annotation.dart';");
  defs.forEach((name, d) {
    final values = d['enum'] as List?;
    if (values == null) return;
    out
      ..writeln()
      ..writeln('/// Values of `$name`.')
      ..writeln('enum $name { ${values.join(', ')} }');
  });
  defs.forEach((name, d) {
    if (d['enum'] != null) return;
    final props = (d['properties'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
    out
      ..writeln()
      ..writeln('/// JSON of `@$name`.')
      ..writeln('class $name extends Annotation {')
      ..writeln(
          '  const $name(${props.isEmpty ? '' : '{${props.keys.map((p) => 'this.${_member(p)}').join(', ')}}'});');
    props.forEach((prop, s) {
      out
        ..writeln()
        ..write(_note(s))
        ..writeln('  final ${_dartType(s)}? ${_member(prop)};');
    });
    out
      ..writeln()
      ..writeln('  @override')
      ..writeln(
          '  Map<String, Object?> get attributes => {${props.keys.map((p) => "'$p': ${_member(p)}").join(', ')}};')
      ..writeln('}');
  });
  return out.toString();
}

String _embed(String constant, String text) {
  if (text.contains("'''")) throw StateError("$constant contains ''', which a raw string cannot hold");
  return "const $constant = r'''$text''';\n";
}

void main(List<String> args) {
  final dir = args.where((a) => !a.startsWith('--')).firstOrNull;
  if (dir == null) {
    stderr.writeln('usage: dart run tool/gen_types.dart <erupt repo>/schema [--check]');
    exit(2);
  }
  String read(String name) {
    final file = File('$dir/$name');
    if (!file.existsSync()) {
      stderr.writeln('missing ${file.path}');
      exit(1);
    }
    return file.readAsStringSync();
  }

  final schema = read('erupt-annotations.schema.json');
  final defaults = read('erupt-node-defaults.json');
  final root = File.fromUri(Platform.script).parent.parent.path;
  final expected = {
    'lib/src/schema.g.dart':
        '// $_header\n// The annotation JSON Schema and the field templates the Java proxies emit.\n\n'
            '${_embed('schemaJson', schema)}\n${_embed('defaultsJson', defaults)}',
    'lib/src/types.g.dart': generateTypes(jsonDecode(schema) as Map<String, dynamic>),
  };
  final stale = expected.entries.where((e) {
    final file = File('$root/${e.key}');
    return !file.existsSync() || file.readAsStringSync() != e.value;
  }).toList();
  final check = args.contains('--check');
  for (final e in stale) {
    if (check) {
      print('stale: dart/${e.key}');
    } else {
      File('$root/${e.key}').writeAsStringSync(e.value);
      print('wrote dart/${e.key}');
    }
  }
  if (check && stale.isNotEmpty) exit(1);
}
