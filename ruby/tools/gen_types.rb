#!/usr/bin/env ruby
# frozen_string_literal: true

# Generate lib/erupt/types.rb (enum constants) and sig/erupt/types.rbs (RBS types of every annotation
# attribute) from the erupt annotation JSON Schema. The gem embeds no schema: the server completes and checks
# builds (erupt-cloud/PROTOCOL.md §12.3).
#
#   ruby tools/gen_types.rb ../schema          # regenerate types
#   ruby tools/gen_types.rb ../schema --check  # fail when anything is out of date (CI)
#
# The input is generated in the erupt repository by erupt-test NodeSchemaTest.
require "json"

ROOT = File.expand_path("..", __dir__)

RBS_PRIMITIVES = { "string" => "String", "integer" => "Integer", "number" => "Numeric", "boolean" => "bool" }.freeze

HEADER = "Generated by tools/gen_types.rb from erupt-annotations.schema.json; do not edit."

def snake(name) = name.gsub(/([a-z0-9])([A-Z])/, '\1_\2').downcase

def rbs_type(schema)
  return snake(schema["$ref"].split("/").last) if schema["$ref"]

  case schema["type"]
  when "array" then "Array[#{rbs_type(schema["items"])}]"
  when "object" then "Hash[Symbol | String, #{schema["additionalProperties"] ? rbs_type(schema["additionalProperties"]) : "untyped"}]"
  else RBS_PRIMITIVES.fetch(schema["type"])
  end
end

def note(schema)
  notes = []
  notes << "default #{JSON.generate(schema["default"])}" if schema.key?("default")
  notes << "only when #{schema["x-erupt-match"]}" if schema["x-erupt-match"]
  notes << "keyed by #{schema["x-erupt-map-key"]}" if schema["x-erupt-map-key"]
  notes.empty? ? "" : " # #{notes.join("; ")}"
end

def generate_ruby(defs)
  out = ["# frozen_string_literal: true", "", "# #{HEADER}", "module Erupt"]
  defs.each do |name, d|
    next unless d["enum"]

    out << "  # Values of +#{name}+: +#{d["enum"].first}+ instead of the string \"#{d["enum"].first}\"."
    out << "  module #{name}"
    d["enum"].each { |v| out << "    #{v} = #{JSON.generate(v)}" }
    out << "  end"
    out << ""
  end
  out.pop
  "#{(out << "end").join("\n")}\n"
end

def generate_rbs(defs)
  out = ["# #{HEADER}", "# Annotation attributes as RBS records: every key is optional, the erupt server completes what a",
         "# declaration leaves out from the defaults the Java proxies emit.", "module Erupt"]
  defs.each do |name, d|
    if d["enum"]
      out << "  type #{snake(name)} = #{d["enum"].map { |v| JSON.generate(v) }.join(" | ")}"
      next
    end
    out << "  type #{snake(name)} = {"
    lines = d["properties"].map { |prop, s| ["    ?#{prop}: #{rbs_type(s)}", note(s)] }
    lines.each_with_index { |(decl, comment), i| out << "#{decl}#{"," if i < lines.size - 1}#{comment}" }
    out << "  }"
  end
  "#{(out << "end").join("\n")}\n"
end

source_dir, *flags = ARGV
abort "usage: ruby tools/gen_types.rb <schema dir> [--check]" if source_dir.nil?
schema = File.join(File.expand_path(source_dir), "erupt-annotations.schema.json")
abort "missing #{schema}" unless File.file?(schema)
defs = JSON.parse(File.read(schema, encoding: "UTF-8"))["$defs"]
expected = { "lib/erupt/types.rb" => generate_ruby(defs), "sig/erupt/types.rbs" => generate_rbs(defs) }

stale = expected.reject { |path, text| File.file?(File.join(ROOT, path)) && File.read(File.join(ROOT, path), encoding: "UTF-8") == text }
if flags.include?("--check")
  stale.each_key { |path| puts "stale: ruby/#{path}" }
  exit(stale.empty? ? 0 : 1)
end
stale.each do |path, text|
  File.write(File.join(ROOT, path), text)
  puts "wrote ruby/#{path}"
end
