// Turns erupt-annotations.schema.json into src/types.rs. Shared by the gen-types binary and the test that
// keeps src/types.rs current, so it depends on nothing but serde_json.
use serde_json::Value;

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
];

fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    if KEYWORDS.contains(&out.as_str()) {
        format!("r#{out}")
    } else {
        out
    }
}

fn pascal(value: &str) -> String {
    value
        .split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let lower = p.to_ascii_lowercase();
            let mut chars = lower.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

fn rust_type(schema: &Value) -> String {
    if let Some(r) = schema.get("$ref").and_then(Value::as_str) {
        return r.rsplit('/').next().unwrap_or(r).to_string();
    }
    match schema["type"].as_str().unwrap_or("") {
        "array" => format!("Vec<{}>", rust_type(&schema["items"])),
        "object" => match schema.get("additionalProperties") {
            Some(item) => format!("BTreeMap<String, {}>", rust_type(item)),
            None => "Map<String, Value>".to_string(),
        },
        "string" => "String".to_string(),
        "integer" => "i64".to_string(),
        "number" => "f64".to_string(),
        "boolean" => "bool".to_string(),
        other => panic!("unmapped schema type {other}"),
    }
}

fn comment(schema: &Value) -> String {
    let mut notes = Vec::new();
    if let Some(d) = schema.get("default") {
        notes.push(format!("default {d}"));
    }
    if let Some(m) = schema.get("x-erupt-match").and_then(Value::as_str) {
        notes.push(format!("only when {m}"));
    }
    if let Some(k) = schema.get("x-erupt-map-key").and_then(Value::as_str) {
        notes.push(format!("keyed by {k}"));
    }
    if notes.is_empty() {
        String::new()
    } else {
        format!("    /// {}\n", notes.join("; "))
    }
}

pub fn generate(schema: &Value) -> String {
    let defs = schema["$defs"].as_object().expect("$defs");
    let mut out = String::from(
        "// Erupt annotation JSON as serde types. Generated by `cargo run --bin gen-types` from\n\
         // erupt-annotations.schema.json; do not edit. Every attribute is optional: a declaration only overrides\n\
         // the defaults the Java proxies emit.\n\
         #![allow(clippy::all, missing_docs)]\n\n\
         use std::collections::BTreeMap;\n\n\
         use serde::{Deserialize, Serialize};\n\
         use serde_json::{Map, Value};\n",
    );
    for (name, def) in defs {
        let Some(values) = def.get("enum").and_then(Value::as_array) else {
            continue;
        };
        let values: Vec<&str> = values.iter().filter_map(Value::as_str).collect();
        let variants: Vec<String> = values.iter().map(|v| pascal(v)).collect();
        let mut seen = std::collections::HashSet::new();
        for v in &variants {
            assert!(
                seen.insert(v.clone()),
                "{name}: two values map to the variant {v}"
            );
        }
        out.push_str(&format!(
            "\n#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum {name} {{\n"
        ));
        for (value, variant) in values.iter().zip(&variants) {
            out.push_str(&format!(
                "    #[serde(rename = \"{value}\")]\n    {variant},\n"
            ));
        }
        out.push_str("}\n\n");
        out.push_str(&format!(
            "impl {name} {{\n    pub const VALUES: &'static [&'static str] = &[{}];\n\n",
            values
                .iter()
                .map(|v| format!("\"{v}\""))
                .collect::<Vec<_>>()
                .join(", ")
        ));
        out.push_str("    pub fn as_str(&self) -> &'static str {\n        match self {\n");
        for (value, variant) in values.iter().zip(&variants) {
            out.push_str(&format!("            Self::{variant} => \"{value}\",\n"));
        }
        out.push_str("        }\n    }\n}\n\n");
        out.push_str(&format!(
            "impl std::str::FromStr for {name} {{\n    type Err = String;\n\n    fn from_str(s: &str) -> Result<Self, String> {{\n        match s {{\n"
        ));
        for (value, variant) in values.iter().zip(&variants) {
            out.push_str(&format!(
                "            \"{value}\" => Ok(Self::{variant}),\n"
            ));
        }
        out.push_str(&format!(
            "            _ => Err(format!(\"'{{s}}' is not a {name}\")),\n        }}\n    }}\n}}\n"
        ));
    }
    for (name, def) in defs {
        if def.get("enum").is_some() {
            continue;
        }
        out.push_str(&format!("\n#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]\npub struct {name} {{\n"));
        for (prop, schema) in def["properties"].as_object().expect("properties") {
            out.push_str(&comment(schema));
            out.push_str(&format!(
                "    #[serde(rename = \"{prop}\", skip_serializing_if = \"Option::is_none\")]\n    pub {}: Option<{}>,\n",
                snake(prop),
                rust_type(schema)
            ));
        }
        out.push_str("}\n");
    }
    out
}
