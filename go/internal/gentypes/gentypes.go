// Package gentypes turns erupt-annotations.schema.json into Go types (types.go of package erupt).
package gentypes

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"
)

// Files the erupt repository generates (erupt-test NodeSchemaTest / NodeDefaultsTest) and the package
// embeds; //go:embed cannot reach ../schema, so they are copied next to the package.
var Files = []string{"erupt-annotations.schema.json", "erupt-node-defaults.json"}

type schema struct {
	Type                 string             `json:"type"`
	Ref                  string             `json:"$ref"`
	Enum                 []string           `json:"enum"`
	Items                *schema            `json:"items"`
	Properties           map[string]*schema `json:"properties"`
	AdditionalProperties json.RawMessage    `json:"additionalProperties"`
	Default              json.RawMessage    `json:"default"`
	Match                string             `json:"x-erupt-match"`
	MapKey               string             `json:"x-erupt-map-key"`
}

// mapValue is the value schema of a map property, nil for an open object.
func (s *schema) mapValue() *schema {
	if len(s.AdditionalProperties) == 0 || s.AdditionalProperties[0] != '{' {
		return nil
	}
	var v schema
	if json.Unmarshal(s.AdditionalProperties, &v) != nil {
		return nil
	}
	return &v
}

// Generate returns the gofmt-ed source of types.go for the given annotation schema.
func Generate(annotationSchema []byte) ([]byte, error) {
	var root struct {
		Defs map[string]*schema `json:"$defs"`
	}
	if err := json.Unmarshal(annotationSchema, &root); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(root.Defs))
	for name := range root.Defs {
		names = append(names, name)
	}
	sort.Strings(names)
	enums := map[string]bool{}
	for _, name := range names {
		enums[name] = root.Defs[name].Enum != nil
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gentypes from erupt-annotations.schema.json; DO NOT EDIT.\n\n")
	b.WriteString("package erupt\n\n")
	for _, name := range names {
		d := root.Defs[name]
		if d.Enum == nil {
			continue
		}
		fmt.Fprintf(&b, "// %s is an erupt enum.\ntype %s string\n\nconst (\n", name, name)
		seen := map[string]bool{}
		for _, v := range d.Enum {
			c := name + constName(v)
			if seen[c] {
				return nil, fmt.Errorf("%s: two values map to %s", name, c)
			}
			seen[c] = true
			fmt.Fprintf(&b, "\t%s %s = %q\n", c, name, v)
		}
		fmt.Fprintf(&b, ")\n\n// %sValues lists every %s in schema order.\nvar %sValues = []%s{", name, name, name, name)
		for i, v := range d.Enum {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(name + constName(v))
		}
		b.WriteString("}\n\n")
	}
	for _, name := range names {
		d := root.Defs[name]
		if d.Enum != nil {
			continue
		}
		fmt.Fprintf(&b, "// %s is the JSON of @%s. Every field is optional: a declaration only overrides the defaults.\n", name, name)
		fmt.Fprintf(&b, "type %s struct {\n", name)
		props := make([]string, 0, len(d.Properties))
		for p := range d.Properties {
			props = append(props, p)
		}
		sort.Strings(props)
		for _, p := range props {
			s := d.Properties[p]
			t, err := goType(s, enums, true)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", name, p, err)
			}
			fmt.Fprintf(&b, "\t%s %s `json:\"%s,omitempty\"`%s\n", exported(p), t, p, comment(s))
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}

// goType maps a property schema; top-level scalars are pointers so false, 0 and "" can be overridden.
func goType(s *schema, enums map[string]bool, top bool) (string, error) {
	if s.Ref != "" {
		name := s.Ref[strings.LastIndex(s.Ref, "/")+1:]
		if enums[name] || !top {
			return name, nil
		}
		return "*" + name, nil
	}
	scalar := map[string]string{"string": "string", "integer": "int64", "number": "float64", "boolean": "bool"}
	switch s.Type {
	case "array":
		t, err := goType(s.Items, enums, false)
		return "[]" + t, err
	case "object":
		v := s.mapValue()
		if v == nil {
			return "map[string]any", nil
		}
		t, err := goType(v, enums, false)
		return "map[string]" + t, err
	}
	t, ok := scalar[s.Type]
	if !ok {
		return "", fmt.Errorf("unknown type %q", s.Type)
	}
	if top {
		return "*" + t, nil
	}
	return t, nil
}

func comment(s *schema) string {
	var notes []string
	if len(s.Default) > 0 {
		var compact bytes.Buffer
		if json.Compact(&compact, s.Default) == nil {
			notes = append(notes, "default "+compact.String())
		}
	}
	if s.Match != "" {
		notes = append(notes, "only when "+s.Match)
	}
	if s.MapKey != "" {
		notes = append(notes, "keyed by "+s.MapKey)
	}
	if len(notes) == 0 {
		return ""
	}
	return " // " + strings.Join(notes, "; ")
}

func exported(name string) string {
	r := []rune(name)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

// constName turns MULTI_ONLY into MultiOnly and text into Text.
func constName(v string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(v, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		r := []rune(strings.ToLower(part))
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	s := b.String()
	if s == "" || unicode.IsDigit([]rune(s)[0]) {
		s = "V" + s
	}
	return s
}
