using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Erupt.GenTypes;

/// <summary>Turns erupt-annotations.schema.json into Types.g.cs.</summary>
public static class Generator
{
    /// <summary>Schema files copied verbatim into the library's embedded resources.</summary>
    public static readonly string[] Resources = ["erupt-annotations.schema.json", "erupt-node-defaults.json"];

    // a type named like the namespace would make every "Erupt" in user code ambiguous
    private static readonly Dictionary<string, string> Renamed = new() { ["Erupt"] = "EruptOptions" };

    private static string Name(string def) => Renamed.GetValueOrDefault(def, def);

    private static readonly Dictionary<string, string> Primitives = new()
    {
        ["string"] = "string", ["integer"] = "long", ["number"] = "double", ["boolean"] = "bool",
    };

    public static string Generate(string schemaJson)
    {
        var defs = JsonNode.Parse(schemaJson)!["$defs"]!.AsObject();
        var sb = new StringBuilder();
        sb.Append("""
            // <auto-generated>
            // Erupt annotation JSON as typed classes. Generated by tools/GenTypes from erupt-annotations.schema.json;
            // do not edit. Every property is optional: a declaration only overrides the defaults the Java proxies emit.
            // </auto-generated>
            #nullable enable
            using System.Text.Json.Nodes;
            using System.Text.Json.Serialization;

            namespace Erupt;

            """.Replace("\r", ""));
        foreach (var (name, def) in defs)
        {
            if (def!["enum"] is not JsonArray values) continue;
            sb.Append('\n').Append($"[JsonConverter(typeof(JsonStringEnumConverter<{name}>))]\n");
            sb.Append($"public enum {name}\n{{\n");
            foreach (var value in values) sb.Append($"    {value!.GetValue<string>()},\n");
            sb.Append("}\n");
        }
        foreach (var (name, def) in defs)
        {
            if (def!["enum"] is not null) continue;
            sb.Append('\n').Append($"/// <summary>JSON of @{name}.</summary>\n");
            sb.Append($"public sealed class {Name(name)}\n{{\n");
            foreach (var (prop, schema) in def["properties"]!.AsObject())
            {
                var member = char.ToUpperInvariant(prop[0]) + prop[1..];
                if (member == Name(name)) member += "Value";
                sb.Append($"    [JsonPropertyName(\"{prop}\")] public {Type(schema!)}? {member} {{ get; set; }}{Comment(schema!)}\n");
            }
            sb.Append("}\n");
        }
        return sb.ToString();
    }

    private static string Type(JsonNode schema)
    {
        if (schema["$ref"] is JsonNode reference) return Name(reference.GetValue<string>().Split('/')[^1]);
        return schema["type"]!.GetValue<string>() switch
        {
            "array" => $"List<{Type(schema["items"]!)}>",
            "object" when schema["additionalProperties"] is JsonNode values => $"Dictionary<string, {Type(values)}>",
            "object" => "JsonObject",
            var kind => Primitives[kind],
        };
    }

    private static string Comment(JsonNode schema)
    {
        var notes = new List<string>();
        if (schema["default"] is JsonNode value) notes.Add("default " + value.ToJsonString(new JsonSerializerOptions { Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }));
        if (schema["x-erupt-match"] is JsonNode match) notes.Add("only when " + match.GetValue<string>());
        if (schema["x-erupt-map-key"] is JsonNode key) notes.Add("keyed by " + key.GetValue<string>());
        return notes.Count == 0 ? "" : " // " + string.Join("; ", notes);
    }
}
