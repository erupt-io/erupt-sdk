// Generates Sources/EruptSDK/Types.swift (enums and typed annotation attributes) and
// Sources/EruptSDK/Embedded.swift (the schema and the field templates, compiled in) from the erupt schemas.
//
//   swift run erupt-gen-types ../schema          # regenerate
//   swift run erupt-gen-types ../schema --check  # fail when anything is out of date (CI)
//
// Inputs are generated in the erupt repository by erupt-test NodeSchemaTest (annotation JSON Schema) and
// NodeDefaultsTest (resolved field templates).
import EruptSDK
import Foundation

let header = "// Code generated by erupt-gen-types from erupt-annotations.schema.json; DO NOT EDIT."
let root = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()

let keywords: Set<String> = [
    "as", "any", "break", "case", "catch", "class", "continue", "default", "defer", "deinit", "do", "else", "enum",
    "extension", "fallthrough", "false", "fileprivate", "for", "func", "guard", "if", "import", "in", "init", "inout",
    "internal", "is", "let", "nil", "open", "operator", "private", "protocol", "public", "repeat", "rethrows", "return",
    "self", "Self", "some", "static", "struct", "subscript", "super", "switch", "throw", "throws", "true", "try",
    "typealias", "var", "where", "while", "Type",
]

func ident(_ name: String) -> String { keywords.contains(name) ? "`\(name)`" : name }

/// DATE_TIME -> dateTime, MULTI_ONLY -> multiOnly, NodeRef -> nodeRef
func caseName(_ value: String) -> String {
    guard value == value.uppercased() else { return value.prefix(1).lowercased() + value.dropFirst() }
    let parts = value.lowercased().split(separator: "_")
    return parts.enumerated().map { i, p in i == 0 ? String(p) : p.prefix(1).uppercased() + p.dropFirst() }.joined()
}

func swiftType(_ schema: JSON) -> String {
    if let ref = schema["$ref"]?.string { return String(ref.split(separator: "/").last!) }
    switch schema["type"]?.string {
    case "string": return "String"
    case "integer": return "Int"
    case "number": return "Double"
    case "boolean": return "Bool"
    case "array": return "[\(swiftType(schema["items"]!))]"
    case "object":
        if let value = schema["additionalProperties"] { return "[String: \(swiftType(value))]" }
        return "JSON"
    default: fatalError("unsupported schema \(schema)")
    }
}

func note(_ schema: JSON) -> String {
    var notes: [String] = []
    if let d = schema["default"] { notes.append("default \(d.serialized())") }
    if let m = schema["x-erupt-match"]?.string { notes.append("only when \(m)") }
    if let k = schema["x-erupt-map-key"]?.string { notes.append("keyed by \(k)") }
    if let d = schema["description"]?.string { notes.append(d) }
    return notes.joined(separator: "; ")
}

func generateTypes(_ defs: [String: JSON]) -> String {
    var out = [header, "", "// swiftlint:disable all", ""]
    for name in defs.keys.sorted() {
        let d = defs[name]!
        if let values = d["enum"]?.array?.compactMap(\.string) {
            out.append("/// Values of `\(name)`.")
            out.append("public enum \(name): String, CaseIterable, Sendable, AnnotationValue {")
            for v in values { out.append("    case \(ident(caseName(v))) = \(JSON.string(v).serialized())") }
            out.append("}")
            out.append("")
            continue
        }
        let props = d["properties"]?.object ?? [:]
        let keys = props.keys.sorted()
        out.append("/// `\(name)` annotation attributes: every one is optional, a declaration only overrides the defaults")
        out.append("/// the Java proxies emit.")
        out.append("public struct \(name): AnnotationValue, Sendable {")
        for key in keys {
            let n = note(props[key]!)
            if !n.isEmpty { out.append("    /// \(n)") }
            out.append("    public var \(ident(key)): \(swiftType(props[key]!))?")
        }
        out.append("")
        if keys.isEmpty {
            out.append("    public init() {}")
        } else {
            out.append("    public init(")
            for (i, key) in keys.enumerated() {
                out.append("        \(ident(key)): \(swiftType(props[key]!))? = nil\(i < keys.count - 1 ? "," : "")")
            }
            out.append("    ) {")
            for key in keys { out.append("        self.\(ident(key)) = \(ident(key))") }
            out.append("    }")
        }
        out.append("")
        out.append("    public var json: JSON {")
        out.append("        var o: [String: JSON] = [:]")
        for key in keys { out.append("        o[\(JSON.string(key).serialized())] = \(ident(key))?.json") }
        out.append("        return .object(o)")
        out.append("    }")
        out.append("}")
        out.append("")
    }
    out.removeLast()
    return out.joined(separator: "\n") + "\n"
}

/// A raw string literal holding `text` verbatim.
func rawLiteral(_ text: String) -> String {
    var hashes = "#"
    while text.contains("\"\"\"" + hashes) || text.contains("\\" + hashes) { hashes += "#" }
    return "\(hashes)\"\"\"\n\(text.hasSuffix("\n") ? String(text.dropLast()) : text)\n\"\"\"\(hashes)"
}

func generateEmbedded(schema: String, defaults: String) -> String {
    """
    \(header)

    /// The contract erupt generates, compiled in: erupt-annotations.schema.json and erupt-node-defaults.json.
    enum Embedded {
        static let annotationsSchema = \(rawLiteral(schema))

        static let nodeDefaults = \(rawLiteral(defaults))
    }

    """
}

let args = CommandLine.arguments.dropFirst()
guard let sourceDir = args.first(where: { !$0.hasPrefix("--") }) else {
    FileHandle.standardError.write("usage: swift run erupt-gen-types <schema dir> [--check]\n".data(using: .utf8)!)
    exit(2)
}
func read(_ name: String) -> String {
    let path = URL(fileURLWithPath: sourceDir).appendingPathComponent(name).path
    guard let text = try? String(contentsOfFile: path, encoding: .utf8) else {
        FileHandle.standardError.write("missing \(path)\n".data(using: .utf8)!)
        exit(2)
    }
    return text
}
let schemaText = read("erupt-annotations.schema.json")
let defaultsText = read("erupt-node-defaults.json")
let defs = try JSON.parse(schemaText)["$defs"]!.object!
let expected = [
    "Sources/EruptSDK/Types.swift": generateTypes(defs),
    "Sources/EruptSDK/Embedded.swift": generateEmbedded(schema: schemaText, defaults: defaultsText),
]
let stale = expected.filter { path, text in
    (try? String(contentsOf: root.appendingPathComponent(path), encoding: .utf8)) != text
}
if args.contains("--check") {
    for path in stale.keys.sorted() { print("stale: swift/\(path)") }
    exit(stale.isEmpty ? 0 : 1)
}
for (path, text) in stale {
    try text.write(to: root.appendingPathComponent(path), atomically: true, encoding: .utf8)
    print("wrote swift/\(path)")
}
