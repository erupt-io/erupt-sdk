<?php
/**
 * Sync the erupt schemas into resources/ and generate src/Types/ from them.
 *
 *   php tools/gen-types.php <erupt schema dir>          copy schemas, regenerate types
 *   php tools/gen-types.php <erupt schema dir> --check  exit 1 when anything is out of date (CI)
 *
 * Inputs are generated in the erupt repository by erupt-test NodeSchemaTest / NodeDefaultsTest.
 */

const PRIMITIVES = ['string' => 'string', 'integer' => 'int', 'number' => 'float', 'boolean' => 'bool'];

function shape_type(array $schema, array $defs): string
{
    if (isset($schema['$ref'])) {
        $name = substr(strrchr($schema['$ref'], '/'), 1);
        // enum-typed attributes travel as their string values
        return isset($defs[$name]['enum']) ? "value-of<\\Erupt\\Types\\$name>" : $name;
    }
    return match ($schema['type']) {
        'array' => 'list<' . shape_type($schema['items'], $defs) . '>',
        'object' => 'array<string, ' . (isset($schema['additionalProperties']) ? shape_type($schema['additionalProperties'], $defs) : 'mixed') . '>',
        default => PRIMITIVES[$schema['type']],
    };
}

/** @return array<string, string> generated file name => content */
function generate(array $schema): array
{
    $files = [];
    $shapes = [];
    foreach ($schema['$defs'] as $name => $def) {
        if (isset($def['enum'])) {
            $cases = '';
            foreach ($def['enum'] as $value) {
                $cases .= "    case $value = '$value';\n";
            }
            $files["$name.php"] = "<?php\n\n// Generated by tools/gen-types.php from erupt-annotations.schema.json; do not edit.\n\n"
                . "namespace Erupt\\Types;\n\nenum $name: string\n{\n$cases}\n";
            continue;
        }
        $props = [];
        foreach ($def['properties'] as $prop => $s) {
            $props[] = "$prop?: " . shape_type($s, $schema['$defs']);
        }
        $shapes[] = " * @phpstan-type $name array{" . implode(', ', $props) . '}';
    }
    $files['Annotations.php'] = "<?php\n\n// Generated by tools/gen-types.php from erupt-annotations.schema.json; do not edit.\n\n"
        . "namespace Erupt\\Types;\n\n/**\n * Erupt annotation JSON as array shapes, for IDE help on raw view / edit / erupt / operation\n"
        . " * attributes. Every key is optional: a declaration only overrides the defaults the Java proxies emit.\n *\n"
        . implode("\n", $shapes) . "\n */\nfinal class Annotations\n{\n}\n";
    return $files;
}

if (PHP_SAPI === 'cli' && realpath($argv[0] ?? '') === __FILE__) {
    $args = array_values(array_filter(array_slice($argv, 1), fn($a) => $a !== '--check'));
    $check = in_array('--check', $argv, true);
    if (count($args) !== 1) {
        fwrite(STDERR, "usage: php tools/gen-types.php <erupt schema dir> [--check]\n");
        exit(2);
    }
    $root = dirname(__DIR__);
    $expected = [];
    foreach (['erupt-annotations.schema.json', 'erupt-node-defaults.json'] as $file) {
        $source = rtrim($args[0], '/') . "/$file";
        if (!is_file($source)) {
            fwrite(STDERR, "missing $source\n");
            exit(2);
        }
        $expected["$root/resources/$file"] = file_get_contents($source);
    }
    $schema = json_decode($expected["$root/resources/erupt-annotations.schema.json"], true, 512, JSON_THROW_ON_ERROR);
    foreach (generate($schema) as $file => $content) {
        $expected["$root/src/Types/$file"] = $content;
    }
    $stale = array_keys(array_filter($expected, fn($content, $path) => !is_file($path) || file_get_contents($path) !== $content, ARRAY_FILTER_USE_BOTH));
    foreach ($stale as $path) {
        $relative = substr($path, strlen($root) + 1);
        if ($check) {
            echo "stale: php/$relative\n";
        } else {
            file_put_contents($path, $expected[$path]);
            echo "wrote php/$relative\n";
        }
    }
    exit($check && $stale ? 1 : 0);
}
