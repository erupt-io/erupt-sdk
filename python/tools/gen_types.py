"""Sync the erupt schemas into the package and generate ``src/erupt/_types.py`` from them.

    python tools/gen_types.py <erupt repo>/schema          # copy schemas, regenerate types
    python tools/gen_types.py <erupt repo>/schema --check  # fail when anything is out of date (CI)

Inputs are generated in the erupt repository by erupt-test ``NodeSchemaTest`` (annotation JSON Schema)
and ``NodeDefaultsTest`` (resolved field templates).
"""
import argparse
import json
import keyword
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "erupt"

# erupt schema file -> copies kept in sync (package resource first, repository copy second)
SCHEMAS = {
    "erupt-annotations.schema.json": [PACKAGE / "_schema.json", ROOT.parent / "schema" / "erupt-annotations.schema.json"],
    "erupt-node-defaults.json": [PACKAGE / "_defaults.json", ROOT.parent / "schema" / "erupt-node-defaults.json"],
}

PRIMITIVES = {"string": "str", "integer": "int", "number": "float", "boolean": "bool"}

PLAIN = set(PRIMITIVES.values()) | {"Dict[str, Any]"}


def py_type(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    kind = schema["type"]
    if kind == "array":
        return f"List[{py_type(schema['items'])}]"
    if kind == "object":
        if "additionalProperties" not in schema:
            return "Dict[str, Any]"
        return f"Dict[str, {py_type(schema['additionalProperties'])}]"
    return PRIMITIVES[kind]


def comment(schema):
    notes = []
    if "default" in schema:
        notes.append("default " + json.dumps(schema["default"], ensure_ascii=False))
    if "x-erupt-match" in schema:
        notes.append("only when " + schema["x-erupt-match"])
    if "x-erupt-map-key" in schema:
        notes.append("keyed by " + schema["x-erupt-map-key"])
    return ("  # " + "; ".join(notes)) if notes else ""


def generate(schema):
    defs = schema["$defs"]
    out = [
        '"""Erupt annotation JSON as typed dicts. Generated by tools/gen_types.py from',
        'erupt-annotations.schema.json; do not edit. Every key is optional: a declaration only overrides',
        'the defaults the Java proxies emit."""',
        "from typing import Any, Dict, List, Literal, TypedDict",
        "",
    ]
    for name, d in defs.items():
        if "enum" in d:
            values = ", ".join(json.dumps(v) for v in d["enum"])
            out.append(f"{name} = Literal[{values}]")
    for name, d in defs.items():
        if "enum" in d:
            continue
        props = d["properties"]
        out += ["", ""]
        if any(keyword.iskeyword(p) or not p.isidentifier() for p in props):
            items = ", ".join(f"{json.dumps(p)}: {json.dumps(py_type(s))}" for p, s in props.items())
            out.append(f"{name} = TypedDict({json.dumps(name)}, {{{items}}}, total=False)")
            continue
        out.append(f"class {name}(TypedDict, total=False):")
        for prop, s in props.items():
            annotation = py_type(s)
            # anything naming another definition is a forward reference
            if annotation not in PLAIN:
                annotation = json.dumps(annotation)
            out.append(f"    {prop}: {annotation}{comment(s)}")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("schema_dir", type=Path, help="the erupt repository's schema directory")
    parser.add_argument("--check", action="store_true", help="report stale files instead of writing them")
    args = parser.parse_args()
    source_dir = args.schema_dir.resolve()
    expected = {}
    for source, targets in SCHEMAS.items():
        path = source_dir / source
        if not path.is_file():
            sys.exit(f"missing {path}")
        text = path.read_text("utf-8")
        for target in targets:
            expected[target] = text
    expected[PACKAGE / "_types.py"] = generate(json.loads(expected[PACKAGE / "_schema.json"]))
    stale = [p for p, text in expected.items() if not p.is_file() or p.read_text("utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT.parent)}")
        sys.exit(1 if stale else 0)
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(expected[p], "utf-8")
        print(f"wrote {p.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
